<#
.SYNOPSIS
	Applies the numbered Infra/Sql scripts (000_*.sql, 001_*.sql, ...) in order to the LOCAL LeozApp database, stopping at the first error.

.EXAMPLE
	.\Infra\Sql\run-local.ps1                                  # apply to LeozApp
	.\Infra\Sql\run-local.ps1 -BuildDeployAll                  # regenerate deploy_all.sql only (no database access)

.NOTES
	Windows authentication only (-E). No password is read, stored or printed.
	Every script also refuses to run on a database other than LeozApp.
#>
param(
	[string]$Server = "DESKTOP-0VOP5VI\SQLEXPRESS",
	[ValidateSet("LeozApp")]
	[string]$Database = "LeozApp",
	[switch]$BuildDeployAll
)

$ErrorActionPreference = "Stop"
$sqlDir = $PSScriptRoot
$scripts = Get-ChildItem -Path $sqlDir -Filter "*.sql" | Where-Object { $_.Name -match '^\d{3}_.+\.sql$' } | Sort-Object Name
if (-not $scripts) { throw "No numbered scripts (000_*.sql ...) found in $sqlDir." }

function Invoke-Sql([string]$db, [string[]]$sqlArgs) {
	& sqlcmd -S $Server -d $db -E -b -I -W -s " | " @sqlArgs
	if ($LASTEXITCODE -ne 0) { throw "sqlcmd failed (exit code $LASTEXITCODE)." }
}

if ($BuildDeployAll) {
	$out = Join-Path $sqlDir "deploy_all.sql"
	$sb = New-Object System.Text.StringBuilder
	[void]$sb.AppendLine("-- deploy_all.sql : GENERATED by Infra/Sql/run-local.ps1 -BuildDeployAll from the numbered scripts. Do not edit by hand.")
	[void]$sb.AppendLine("-- Production : connect to the application database, set @Target below to its name, run the whole file.")
	[void]$sb.AppendLine("-- Re-runnable : each script is skipped when already logged in dbo.SchemaScriptLog.")
	[void]$sb.AppendLine("-- Every script aborts (SET NOEXEC ON) when the connected database is not @Target / LeozApp,")
	[void]$sb.AppendLine("-- and a script whose predecessor failed refuses to run.")
	[void]$sb.AppendLine("")
	[void]$sb.AppendLine("DECLARE @Target SYSNAME = N'<PRODUCTION_DATABASE_NAME>';")
	[void]$sb.AppendLine("IF @Target = N'<PRODUCTION_DATABASE_NAME>' OR @Target <> DB_NAME()")
	[void]$sb.AppendLine("BEGIN")
	[void]$sb.AppendLine("`tRAISERROR(N'deploy_all.sql : set @Target to the name of the database you are connected to. Aborted.', 16, 1);")
	[void]$sb.AppendLine("`tSET NOEXEC ON;")
	[void]$sb.AppendLine("END")
	[void]$sb.AppendLine("ELSE")
	[void]$sb.AppendLine("`tEXEC sys.sp_set_session_context @key = N'Leoz.TargetDb', @value = @Target;")
	[void]$sb.AppendLine("GO")
	foreach ($s in $scripts) {
		[void]$sb.AppendLine("")
		[void]$sb.AppendLine("-- =====================================================================================")
		[void]$sb.AppendLine("-- $($s.Name)")
		[void]$sb.AppendLine("-- =====================================================================================")
		[void]$sb.AppendLine((Get-Content -Path $s.FullName -Raw -Encoding UTF8).TrimEnd())
	}
	[System.IO.File]::WriteAllText($out, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
	Write-Host "Generated $out from $($scripts.Count) script(s)."
	return
}

Write-Host "Server $Server, database $Database"
Invoke-Sql $Database @("-Q", "SET NOCOUNT ON; SELECT DB_NAME() AS [Database];")

foreach ($s in $scripts) {
	Write-Host ""
	Write-Host "==> $($s.Name)"
	Invoke-Sql $Database @("-i", $s.FullName)
}

Write-Host ""
Write-Host "All $($scripts.Count) script(s) applied to $Database."
