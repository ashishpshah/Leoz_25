<#
.SYNOPSIS
	Applies the numbered Infra/Sql scripts (000_*.sql, 001_*.sql, ...) in order to a LOCAL database, stopping at the first error.

.EXAMPLE
	.\Infra\Sql\run-local.ps1                                  # apply to LeozApp
	.\Infra\Sql\run-local.ps1 -Database LeozApp_Test           # apply to the test database
	.\Infra\Sql\run-local.ps1 -CreateTestDb -FromBackup D:\Backup\LeozApp_pre_permissions.bak
	                                                           # (re)create LeozApp_Test from a LeozApp backup, then apply
	.\Infra\Sql\run-local.ps1 -BuildDeployAll                  # regenerate deploy_all.sql only (no database access)

.NOTES
	Windows authentication only (-E). No password is read, stored or printed.
	Every script also refuses to run on a database other than LeozApp / LeozApp_Test.
#>
param(
	[string]$Server = "DESKTOP-0VOP5VI\SQLEXPRESS",
	[ValidateSet("LeozApp", "LeozApp_Test")]
	[string]$Database = "LeozApp",
	[switch]$CreateTestDb,
	[string]$FromBackup,
	[switch]$BuildDeployAll
)

$ErrorActionPreference = "Stop"
$sqlDir = $PSScriptRoot
$scripts = Get-ChildItem -Path $sqlDir -Filter "*.sql" | Where-Object { $_.Name -match '^\d{3}_.+\.sql$' } | Sort-Object Name
if (-not $scripts) { throw "No numbered scripts (000_*.sql ...) found in $sqlDir." }

function Invoke-Sql([string]$db, [string[]]$sqlArgs) {
	& sqlcmd -S $Server -d $db -E -b -I -W -s " | " @sqlArgs
	if ($LASTEXITCODE -ne 0) { throw "sqlcmd failed (exit code $LASTEXITCODE)." }
}

if ($BuildDeployAll) {
	$out = Join-Path $sqlDir "deploy_all.sql"
	$sb = New-Object System.Text.StringBuilder
	[void]$sb.AppendLine("-- deploy_all.sql : GENERATED by Infra/Sql/run-local.ps1 -BuildDeployAll from the numbered scripts. Do not edit by hand.")
	[void]$sb.AppendLine("-- Production : connect to the application database, set @Target below to its name, run the whole file.")
	[void]$sb.AppendLine("-- Re-runnable : each script is skipped when already logged in dbo.SchemaScriptLog.")
	[void]$sb.AppendLine("-- Every script aborts (SET NOEXEC ON) when the connected database is not @Target / LeozApp / LeozApp_Test,")
	[void]$sb.AppendLine("-- and a script whose predecessor failed refuses to run.")
	[void]$sb.AppendLine("")
	[void]$sb.AppendLine("DECLARE @Target SYSNAME = N'<PRODUCTION_DATABASE_NAME>';")
	[void]$sb.AppendLine("IF @Target = N'<PRODUCTION_DATABASE_NAME>' OR @Target <> DB_NAME()")
	[void]$sb.AppendLine("BEGIN")
	[void]$sb.AppendLine("`tRAISERROR(N'deploy_all.sql : set @Target to the name of the database you are connected to. Aborted.', 16, 1);")
	[void]$sb.AppendLine("`tSET NOEXEC ON;")
	[void]$sb.AppendLine("END")
	[void]$sb.AppendLine("ELSE")
	[void]$sb.AppendLine("`tEXEC sys.sp_set_session_context @key = N'Leoz.TargetDb', @value = @Target;")
	[void]$sb.AppendLine("GO")
	foreach ($s in $scripts) {
		[void]$sb.AppendLine("")
		[void]$sb.AppendLine("-- =====================================================================================")
		[void]$sb.AppendLine("-- $($s.Name)")
		[void]$sb.AppendLine("-- =====================================================================================")
		[void]$sb.AppendLine((Get-Content -Path $s.FullName -Raw -Encoding UTF8).TrimEnd())
	}
	[System.IO.File]::WriteAllText($out, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
	Write-Host "Generated $out from $($scripts.Count) script(s)."
	return
}

if ($CreateTestDb) {
	if ($Database -ne "LeozApp_Test") { $Database = "LeozApp_Test" }
	if (-not $FromBackup -or -not (Test-Path $FromBackup)) { throw "-CreateTestDb needs -FromBackup <path of a LeozApp .bak>." }

	# Logical file names of the backup, moved next to the instance's default data / log folders
	$files = & sqlcmd -S $Server -d master -E -b -h -1 -W -s "|" -Q "SET NOCOUNT ON; RESTORE FILELISTONLY FROM DISK = N'$FromBackup';" |
		Where-Object { $_ -match "\|" } | ForEach-Object { $c = $_.Split("|"); [pscustomobject]@{ Logical = $c[0]; Type = $c[2] } }
	if ($LASTEXITCODE -ne 0 -or -not $files) { throw "Could not read the backup file list." }

	$paths = & sqlcmd -S $Server -d master -E -b -h -1 -W -s "|" -Q "SET NOCOUNT ON; SELECT CAST(SERVERPROPERTY('InstanceDefaultDataPath') AS NVARCHAR(400)) + N'|' + CAST(SERVERPROPERTY('InstanceDefaultLogPath') AS NVARCHAR(400));"
	$dataPath, $logPath = ($paths | Where-Object { $_ -match "\|" } | Select-Object -First 1).Split("|")

	$moves = ($files | ForEach-Object {
		$ext = if ($_.Type -eq "L") { "ldf" } else { "mdf" }
		$dir = if ($_.Type -eq "L") { $logPath } else { $dataPath }
		"MOVE N'$($_.Logical)' TO N'$($dir)LeozApp_Test_$($_.Logical).$ext'"
	}) -join ", "

	Write-Host "Restoring LeozApp_Test from backup ..."
	Invoke-Sql "master" @("-Q", "IF DB_ID(N'LeozApp_Test') IS NOT NULL ALTER DATABASE [LeozApp_Test] SET SINGLE_USER WITH ROLLBACK IMMEDIATE; RESTORE DATABASE [LeozApp_Test] FROM DISK = N'$FromBackup' WITH REPLACE, $moves; ALTER DATABASE [LeozApp_Test] SET MULTI_USER;")
}

Write-Host "Server $Server, database $Database"
Invoke-Sql $Database @("-Q", "SET NOCOUNT ON; SELECT DB_NAME() AS [Database];")

foreach ($s in $scripts) {
	Write-Host ""
	Write-Host "==> $($s.Name)"
	Invoke-Sql $Database @("-i", $s.FullName)
}

Write-Host ""
Write-Host "All $($scripts.Count) script(s) applied to $Database."
